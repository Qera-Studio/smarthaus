/** A name the schema no longer offers fails the build, never draws nothing. */
export function solutionIcon(name: string): LucideIcon {
  const icon = (SOLUTION_ICON as Record<string, LucideIcon | undefined>)[name];
  if (!icon) throw new Error(`Solution page: no icon "${name}" (SOLUTION_ICONS)`);
  return icon;
}
